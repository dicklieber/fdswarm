package fdswarm.exporter

import fdswarm.fx.contest.{ContestConfig, ContestTypes}
import fdswarm.importer.AdifRecordParser
import fdswarm.model.*
import munit.FunSuite

import java.time.Instant

class AdifExporterTest extends FunSuite:
  val qsoMetadata = fdswarm.model.QsoMetadata.testQsoMetadata

  val config = ContestConfig(ContestTypes.configured("ARRL"), Callsign("WM9W"), 20, "A", "IL")
  val exporter = new AdifExporter(null, null)

  test("AdifExporter should generate correct ADIF"):
    val bandMode = BandMode("40M", "CW")
    val stamp = Instant.parse("2026-02-25T10:00:00Z")
    val qso = Qso(
      callsign = Callsign("K1ABC"),
      exchange = Exchange(FdClass("1A"), "CT"),
      bandMode = bandMode,
      qsoMetadata = fdswarm.model.QsoMetadata.testQsoMetadata,
      stamp = stamp,
      uuid = "unique-id-123"
    )

    val adif = exporter.exportQsos(Seq(qso), config)
    
    // Check header
    assert(adif.contains("Generated by FdSwarm"))
    assert(adif.contains("<ADIF_VER:5>3.1.4"))
    assert(adif.contains("<EOH>"))
    
    // Check record
    assert(adif.contains("<CALL:5>K1ABC"))
    assert(adif.contains("<BAND:3>40M"))
    assert(adif.contains("<MODE:2>CW"))
    assert(adif.contains("<QSO_DATE:8>20260225"))
    assert(adif.contains("<TIME_ON:6>100000"))
    assert(adif.contains("<STATION_CALLSIGN:4>WM9W"))
    assert(adif.contains("<CLASS:2>1A"))
    assert(adif.contains("<ARRL_SECT:2>CT"))
    assert(adif.contains("<EOR>"))

  test("AdifExporter should map internal modes to ADIF modes"):
    val stamp = Instant.parse("2026-02-25T10:00:00Z")

    val qsoPh = Qso(Callsign("K1ABC"), Exchange(FdClass("1A"), "CT"), BandMode("40M", "PH"), qsoMetadata, stamp, "id-ph")
    val qsoDigi = Qso(Callsign("K1ABC"), Exchange(FdClass("1A"), "CT"), BandMode("40M", "DIGI"), qsoMetadata, stamp, "id-digi")
    val qsoCw = Qso(Callsign("K1ABC"), Exchange(FdClass("1A"), "CT"), BandMode("40M", "CW"), qsoMetadata, stamp, "id-cw")

    val adif = exporter.exportQsos(Seq(qsoPh, qsoDigi, qsoCw), config)
    
    assert(adif.contains("<MODE:3>SSB"), "PH should map to SSB")
    assert(adif.contains("<APP_FDSWARM_MODE:4>DIGI"), "Generic digital must be preserved without inventing an ADIF mode")
    assert(!adif.contains("<MODE:4>DATA"))
    assert(adif.contains("<MODE:2>CW"), "CW should remain CW")

  test("generic digital records round trip with UTC seconds, UUID and per-QSO operator intact"):
    val original = Qso(Callsign("WA9AAB"), Exchange(FdClass("6H"), "IL"), BandMode("4m DIGI"),
      qsoMetadata.withOperator(Callsign("WB9HWE")), Instant.parse("2026-10-23T15:11:09Z"), "digital-id")
    val adif = exporter.exportQsos(Seq(original), config)
    val record = adif.substring(adif.indexOf("<EOH>") + 5)
    val parser = new AdifRecordParser(() => qsoMetadata, _ => Mode.PH)
    val fields = parser.extractFields(record)
    assertEquals(fields("STATION_CALLSIGN"), "WM9W")
    assertEquals(fields("OPERATOR"), "WB9HWE")
    assertEquals(fields("TIME_ON"), "151109")
    assert(!fields.contains("MODE"))
    assertEquals(parser.parseRecord(record).get, original)
