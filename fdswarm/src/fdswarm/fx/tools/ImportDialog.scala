package fdswarm.fx.tools

import fdswarm.fx.UserConfig
import fdswarm.fx.utils.StyledDialog
import fdswarm.importer.{QsoError, QsoFileImporter, QsoImportFormat, QsoImportResult}
import fdswarm.logging.LazyStructuredLogging
import fdswarm.util.FilenameStamp
import jakarta.inject.{Inject, Singleton}
import javafx.concurrent.{Task as JfxTask}
import javafx.event.ActionEvent
import scalafx.Includes.*
import scalafx.beans.property.StringProperty
import scalafx.geometry.Insets
import scalafx.scene.control.*
import scalafx.scene.layout.*
import scalafx.stage.{FileChooser, Window}
import scalafx.stage.FileChooser.ExtensionFilter

@Singleton
final class ImportDialog @Inject()(
    importer: QsoFileImporter,
    filenameStamp: FilenameStamp,
    userConfig: UserConfig
) extends LazyStructuredLogging:

  def show(ownerWindow: Window): Unit =
    val selectedPath = StringProperty("")
    val lastImportDir = userConfig.getProperty[StringProperty]("lastImportDirectory")
    var done = false
    var running = false

    def reportLabel(initial: String = ""): Label = new Label(initial):
      wrapText = true
      minWidth = 0
      minHeight = Region.USE_PREF_SIZE
      maxWidth = Double.MaxValue

    val filePathLabel = reportLabel("Select a QSO journal or ADIF file.")
    selectedPath.onChange { (_, _, path) =>
      filePathLabel.text = if path.isEmpty then "Select a QSO journal or ADIF file." else path
    }
    val browseButton = new Button("Browse…"):
      minWidth = Region.USE_PREF_SIZE
      onAction = _ =>
        val chooser = new FileChooser:
          title = "Select QSO Import File"
          extensionFilters ++= Seq(
            new ExtensionFilter("QSO Files", Seq("*.json", "*.adi", "*.adif", "*.JSON", "*.ADI", "*.ADIF")),
            new ExtensionFilter("QSO Journal (*.json)", Seq("*.json", "*.JSON")),
            new ExtensionFilter("ADIF (*.adi, *.adif)", Seq("*.adi", "*.adif", "*.ADI", "*.ADIF"))
          )
          val savedDir = new java.io.File(lastImportDir.value)
          if lastImportDir.value.nonEmpty && savedDir.isDirectory then initialDirectory = savedDir
        val file = chooser.showOpenDialog(ownerWindow)
        if file != null then
          selectedPath.value = file.getAbsolutePath
          lastImportDir.value = file.getParent

    HBox.setHgrow(filePathLabel, Priority.Always)
    val fileRow = new HBox(8, filePathLabel, browseButton)
    val progressBar = new ProgressBar:
      maxWidth = Double.MaxValue
      managed = false
      visible = false
    val progressLabel = reportLabel()
    progressLabel.managed = false
    progressLabel.visible = false

    val includeOlderCheckBox = new CheckBox("Include QSOs older than two months"):
      selected = false
      tooltip = new Tooltip("This helps avoiding importing from a previous Field Day."):
        wrapText = true
      wrapText = true
      minHeight = Region.USE_PREF_SIZE

    val resultIgnoredLabel = reportLabel()
    val resultTotalLabel = reportLabel()
    val resultParsedLabel = reportLabel()
    val resultSuccessLabel = reportLabel()
    val resultDupLabel = reportLabel()
    val resultErrorLabel = reportLabel()
    val errorListArea = new TextArea:
      editable = false
      prefHeight = 250
      wrapText = true

    // Only read and written on the FX thread.
    var failedErrors: List[QsoError] = Nil
    var failedFormat = QsoImportFormat.Adif
    val saveFailedButton = new Button("Save Failed Records…"):
      minWidth = Region.USE_PREF_SIZE
      managed = false
      visible = false
      onAction = _ =>
        val journal = failedFormat == QsoImportFormat.Journal
        val extension = if journal then "json" else "adi"
        val chooser = new FileChooser:
          title = "Save Failed Import Records"
          initialFileName = s"${filenameStamp.build()}-failed.$extension"
          extensionFilters += (if journal then
            new ExtensionFilter("JSON Lines", Seq("*.json"))
          else new ExtensionFilter("ADIF Files", Seq("*.adi", "*.adif")))
        val file = chooser.showSaveDialog(ownerWindow)
        if file != null then
          val text = if journal then failedErrors.map(_.record).mkString("", "\n", "\n")
          else
            val header = "Generated by FdSwarm – Failed Import Records\n<ADIF_VER:5>3.1.4\n<EOH>\n"
            header + failedErrors.map(error => error.record.trim + "\n<EOR>").mkString("\n")
          os.write.over(os.Path(file.getAbsolutePath), text)

    val resultsBox = new VBox(4,
      new Separator, reportLabel("Import Results:"), resultTotalLabel, resultParsedLabel,
      resultSuccessLabel, resultIgnoredLabel, resultDupLabel, resultErrorLabel, errorListArea, saveFailedButton):
      managed = false
      visible = false
      padding = Insets(8, 0, 0, 0)

    val contentPane = new VBox(8,
      reportLabel("Import File:"), fileRow,
      reportLabel("JSON journals merge by UUID and preserve original timestamps and metadata, just like node synchronization. ADIF retains its existing callsign/band/mode duplicate checks."),
      includeOlderCheckBox, progressBar, progressLabel, resultsBox):
      padding = Insets(20)

    val importButtonType = new ButtonType("Import", ButtonBar.ButtonData.OKDone)
    val dialog = new StyledDialog[Unit]:
      initOwner(ownerWindow)
      title = "Import QSOs"
      headerText = "Import a QSO journal or ADIF file"
      resizable = true
    dialog.dialogPane().buttonTypes = Seq(importButtonType, ButtonType.Cancel)
    dialog.dialogPane().content = new ScrollPane:
      content = contentPane
      fitToWidth = true
      prefViewportWidth = 750
      prefViewportHeight = 520
    dialog.resultConverter = _ => ()
    dialog.delegate.setOnCloseRequest(event => if running then event.consume())

    val importNode = dialog.dialogPane().lookupButton(importButtonType)
      .asInstanceOf[javafx.scene.control.Button]
    val cancelNode = dialog.dialogPane().lookupButton(ButtonType.Cancel.delegate)
      .asInstanceOf[javafx.scene.control.Button]
    importNode.setMinWidth(Region.USE_PREF_SIZE)
    cancelNode.setMinWidth(Region.USE_PREF_SIZE)
    importNode.disable = true
    selectedPath.onChange { (_, _, path) =>
      if !done then importNode.disable = path.isEmpty
    }

    def showProgress(): Unit =
      Seq(progressBar.delegate, progressLabel.delegate).foreach { node =>
        node.setManaged(true)
        node.setVisible(true)
      }

    importNode.addEventFilter(ActionEvent.ACTION, (event: ActionEvent) => {
      if !done then
        event.consume()
        val filePath = selectedPath.value
        if filePath.nonEmpty then
          val includeOlder = includeOlderCheckBox.selected.value
          includeOlderCheckBox.disable = true
          running = true
          importNode.disable = true
          browseButton.disable = true
          cancelNode.disable = true
          showProgress()
          val task = new JfxTask[QsoImportResult]:
            override def call(): QsoImportResult =
              updateMessage("Reading import file…")
              importer.importFile(new java.io.File(filePath), (processed, total) => {
                updateProgress(processed, total)
                updateMessage(s"$processed of $total records processed")
              }, includeOlderThanTwoMonths = includeOlder)
          progressBar.progress <== task.progressProperty()
          progressLabel.text <== task.messageProperty()

          task.onSucceeded = _ =>
            running = false
            val result = task.getValue
            progressBar.progressProperty().unbind()
            progressLabel.textProperty().unbind()
            progressBar.progress = 1.0
            progressLabel.text = "Import complete."
            failedErrors = result.failedRecords
            failedFormat = result.format
            def fmt(n: Int): String = "%,d".formatLocal(java.util.Locale.getDefault, n)
            val journal = result.format == QsoImportFormat.Journal
            resultTotalLabel.text = s"Total records in file: ${fmt(result.totalRecords)}"
            resultParsedLabel.text = s"Parsed QSO records: ${fmt(result.parsedRecords)}"
            resultIgnoredLabel.text = s"Ignored (older than two months): ${fmt(result.ignoredOlder)}"
            resultSuccessLabel.text = s"Successfully added: ${fmt(result.added)}"
            val policy = if journal then "same UUID" else "same callsign/band/mode"
            resultDupLabel.text = s"Duplicates rejected ($policy): ${fmt(result.duplicates)}"
            val errorUnit = if journal then "Line" else "Record"
            resultErrorLabel.text = s"$errorUnit parse errors: ${fmt(result.parseErrors.size)}"
            errorListArea.text = if failedErrors.isEmpty then
              if journal then "No line parse errors." else "No rejected records."
            else failedErrors.map(error => s"${error.message}\n${error.record}").mkString("\n\n")
            saveFailedButton.text = if journal then "Save Lines with Parse Errors…" else "Save Failed Records as ADIF…"
            saveFailedButton.managed = failedErrors.nonEmpty
            saveFailedButton.visible = failedErrors.nonEmpty
            resultsBox.managed = true
            resultsBox.visible = true
            done = true
            importNode.disable = false
            importNode.text = "Close"
            cancelNode.disable = false

          task.onFailed = _ =>
            running = false
            val error = task.getException
            logger.error("QSO import task failed", error, "file" -> filePath)
            progressBar.progressProperty().unbind()
            progressLabel.textProperty().unbind()
            progressBar.progress = 0
            progressLabel.text = s"Import failed: ${Option(error.getMessage).getOrElse(error.getClass.getSimpleName)}"
            importNode.disable = false
            includeOlderCheckBox.disable = false
            browseButton.disable = false
            cancelNode.disable = false

          val thread = new Thread(task, "qso-import")
          thread.setDaemon(true)
          thread.start()
    })
    dialog.showAndWait()
