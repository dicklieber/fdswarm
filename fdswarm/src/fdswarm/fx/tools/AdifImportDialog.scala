package fdswarm.fx.tools

import fdswarm.exporter.AdifExporter
import fdswarm.fx.UserConfig
import fdswarm.importer.{AdifRecordParser, QsoError}
import fdswarm.logging.LazyStructuredLogging
import fdswarm.model.*
import fdswarm.store.QsoStore
import fdswarm.util.FilenameStamp
import jakarta.inject.{Inject, Singleton}
import javafx.concurrent.{Task as JfxTask}
import javafx.event.ActionEvent
import scalafx.Includes.*
import scalafx.geometry.Insets
import scalafx.scene.control.*
import scalafx.scene.layout.*
import scalafx.stage.{FileChooser, Window}
import scalafx.stage.FileChooser.ExtensionFilter

import java.io.FileInputStream

/** A parse result pairing the raw ADIF record text with its parse outcome. */
private case class RecordResult(rawRecord: String, result: Either[QsoError, Qso])

@Singleton
final class AdifImportDialog @Inject()(
    qsoStore: QsoStore,
    adifExporter: AdifExporter,
    filenameStamp: FilenameStamp,
    userConfig: UserConfig
) extends LazyStructuredLogging:

  def show(ownerWindow: Window): Unit =

    // ── file-selection row ──────────────────────────────────────────────────
    val filePathField = new TextField:
      promptText = "Select ADIF file…"
      editable = false

    val lastImportDir = userConfig.getProperty[scalafx.beans.property.StringProperty]("lastImportDirectory")

    val browseButton = new Button("Browse…"):
      onAction = _ =>
        val chooser = new FileChooser:
          title = "Select ADIF File"
          extensionFilters ++= Seq(
            new ExtensionFilter("ADIF Files", Seq("*.adi", "*.adif")),
            new ExtensionFilter("All Files", Seq("*.*"))
          )
          val savedDir = lastImportDir.value
          if savedDir.nonEmpty then
            val d = new java.io.File(savedDir)
            if d.isDirectory then initialDirectory = d
        val file = chooser.showOpenDialog(ownerWindow)
        if file != null then
          filePathField.text = file.getAbsolutePath
          lastImportDir.value = file.getParent

    HBox.setHgrow(filePathField, javafx.scene.layout.Priority.ALWAYS)
    val fileRow = new HBox(5, filePathField, browseButton)

    // ── progress row ────────────────────────────────────────────────────────
    val progressBar = new ProgressBar:
      maxWidth = Double.MaxValue
      managed = false
      visible = false

    val progressLabel = new Label(""):
      managed = false
      visible = false

    // ── results section ─────────────────────────────────────────────────────
    val resultTotalLabel   = new Label
    val resultSuccessLabel = new Label
    val resultDupLabel     = new Label
    val resultErrorLabel   = new Label

    val errorListArea = new TextArea:
      editable   = false
      prefHeight = 250
      wrapText   = true

    // failedErrors is mutated from the FX thread in onSucceeded, then read from
    // the Save-button handler – both on the FX thread, so no locking needed.
    var failedErrors: List[QsoError] = Nil

    val saveFailedButton = new Button("Save Failed Records as ADIF…"):
      managed = false
      visible = false
      onAction = _ =>
        val chooser = new FileChooser:
          title = "Save Failed Records"
          initialFileName = s"${filenameStamp.build()}-failed.adi"
          extensionFilters ++= Seq(
            new ExtensionFilter("ADIF Files", Seq("*.adi", "*.adif")),
            new ExtensionFilter("All Files", Seq("*.*"))
          )
        val file = chooser.showSaveDialog(ownerWindow)
        if file != null then
          val header  = "Generated by FdSwarm – Failed Import Records\n<ADIF_VER:5>3.1.4\n<EOH>\n"
          val records = failedErrors.map(e => e.record.trim + "\n<EOR>").mkString("\n")
          os.write.over(os.Path(file.getAbsolutePath), header + records)

    val resultsBox = new VBox(4,
      new Separator,
      new Label("Import Results:"),
      resultTotalLabel,
      resultSuccessLabel,
      resultDupLabel,
      resultErrorLabel,
      errorListArea,
      saveFailedButton
    ):
      managed = false
      visible = false
      padding = Insets(8, 0, 0, 0)

    // ── content pane ────────────────────────────────────────────────────────
    val content = new VBox(8,
      new Label("ADIF File:"),
      fileRow,
      progressBar,
      progressLabel,
      resultsBox
    ):
      padding = Insets(20)
      prefWidth = 750
      prefHeight = 520

    // ── dialog ──────────────────────────────────────────────────────────────
    val importButtonType = new ButtonType("Import", ButtonBar.ButtonData.OKDone)

    val dialog = new Dialog[Unit]:
      initOwner(ownerWindow)
      title      = "Import ADIF"
      headerText = "Import QSOs from ADIF File"
      resizable  = true

    dialog.dialogPane().buttonTypes = Seq(importButtonType, ButtonType.Cancel)
    dialog.dialogPane().content     = content
    dialog.resultConverter          = _ => ()

    val importNode = dialog.dialogPane()
      .lookupButton(importButtonType)
      .asInstanceOf[javafx.scene.control.Button]

    val cancelNode = dialog.dialogPane()
      .lookupButton(ButtonType.Cancel.delegate)
      .asInstanceOf[javafx.scene.control.Button]

    // Disable Import until a file is chosen
    importNode.disable = true
    filePathField.text.onChange { (_, _, v) =>
      if !importNode.text.value.startsWith("C") then // not "Close"
        importNode.disable = v == null || v.isEmpty
    }

    // Intercept the Import button to prevent the dialog from closing on first click
    var done = false
    importNode.addEventFilter(ActionEvent.ACTION, (event: ActionEvent) => {
      if !done then
        event.consume()
        val filePath = filePathField.text.value
        if filePath.nonEmpty then
          importNode.disable = true
          browseButton.disable = true
          cancelNode.disable  = true
          showProgress(managed = true, visible = true, progressBar, progressLabel)

          val task = buildParseTask(filePath)
          progressBar.progress <== task.progressProperty()
          progressLabel.text   <== task.messageProperty()

          task.onSucceeded = _ =>
            val recordResults: List[RecordResult] = task.getValue.asInstanceOf[List[RecordResult]]

            progressBar.progressProperty().unbind()
            progressLabel.textProperty().unbind()
            progressBar.progress = 1.0
            progressLabel.text   = "Processing complete."

            val parseErrors = recordResults.collect { case RecordResult(_, Left(err)) => err }

            val (successCount, importDups) =
              recordResults.foldLeft((0, List.empty[QsoError])) {
                case ((cnt, dups), RecordResult(raw, Right(qso))) =>
                  val msg = qsoStore.add(qso)
                  if msg.css == "duplicate-qso" then
                    (cnt, QsoError(raw, Exception(msg.text)) :: dups)
                  else
                    (cnt + 1, dups)
                case (acc, RecordResult(_, Left(_))) => acc
              }

            failedErrors = parseErrors ++ importDups

            def fmt(n: Int): String = "%,d".formatLocal(java.util.Locale.getDefault, n)
            resultTotalLabel.text   = s"Total records in file: ${fmt(recordResults.size)}"
            resultSuccessLabel.text = s"Successfully added:     ${fmt(successCount)}"
            resultDupLabel.text     = s"Duplicates (skipped):   ${fmt(importDups.size)}"
            resultErrorLabel.text   = s"Parse errors:           ${fmt(parseErrors.size)}"

            if failedErrors.nonEmpty then
              val sb = new StringBuilder
              failedErrors.foreach { err =>
                val snippet = if err.record.length > 120 then err.record.take(120) + "…"
                              else err.record
                sb.append(err.exception.getMessage).append("\n  ").append(snippet).append("\n\n")
              }
              errorListArea.text = sb.toString.trim
            else
              errorListArea.text = "(none)"

            showManagedVisible(failedErrors.nonEmpty, saveFailedButton)
            showProgress(managed = true, visible = true, progressBar, progressLabel)
            showManagedVisible(managed = true, resultsBox)

            done = true
            importNode.disable = false
            importNode.text    = "Close"
            cancelNode.disable = false

          task.onFailed = _ =>
            val ex = task.getException
            logger.error("ADIF import task failed", ex)
            progressBar.progressProperty().unbind()
            progressLabel.textProperty().unbind()
            progressLabel.text = s"Import failed: ${Option(ex.getMessage).getOrElse(ex.getClass.getSimpleName)}"
            importNode.disable = false
            cancelNode.disable = false

          val thread = new Thread(task, "adif-import")
          thread.setDaemon(true)
          thread.start()
    })

    dialog.showAndWait()

  // ── helpers ────────────────────────────────────────────────────────────────

  private def buildParseTask(filePath: String): JfxTask[List[RecordResult]] =
    new JfxTask[List[RecordResult]] {
      override def call(): List[RecordResult] =
        val is = new FileInputStream(filePath)
        try
          val content  = scala.io.Source.fromInputStream(is, "UTF-8").mkString
          val eohIdx   = "(?i)<eoh>".r.findFirstMatchIn(content).map(_.end).getOrElse(0)
          val body     = content.substring(eohIdx)
          val rawRecs  = body.split("(?i)<eor>").toSeq.map(_.trim).filter(_.nonEmpty)
          val total    = rawRecs.size.toLong
          val fmtL     = (n: Long) => "%,d".formatLocal(java.util.Locale.getDefault, n)
          updateMessage(s"0 of ${fmtL(total)} records parsed…")
          rawRecs.zipWithIndex.map { case (raw, idx) =>
            updateProgress(idx.toLong + 1L, total)
            updateMessage(s"${fmtL(idx.toLong + 1L)} of ${fmtL(total)} records parsed…")
            val either = AdifRecordParser().parseRecord(raw).toEither.left.map { t =>
              val ex = t match
                case e: Exception => e
                case _            => RuntimeException(t.getMessage, t)
              QsoError(raw, ex)
            }
            RecordResult(raw, either)
          }.toList
        finally is.close()
    }

  private def showProgress(managed: Boolean, visible: Boolean, nodes: javafx.scene.Node*): Unit =
    nodes.foreach { n => n.setManaged(managed); n.setVisible(visible) }

  private def showManagedVisible(managed: Boolean, node: javafx.scene.Node): Unit =
    node.setManaged(managed); node.setVisible(managed)
